# for loop : a control flow statement used to iterate over a sequence (like a list, tuple, dictionary, set, or string) or any other iterable object
# for loop = finite ( limited )
# while loop = infinite ( unlimited )


# Numbers from 1 to 10
for i in range(10):
    print(i+1)

# Numbers from 50 to 100
for j in range(50,100+1):
    print(j)

# Even numbers from 50 to 100
for k in range(20,100+1,2):
    print(k)

# Each letter in the string in order
for l in "Nitisha Karna":
    print(l)

    